function normalize(text: string): string {
  return text.toLowerCase()
    .replace(/fund/g, '')
    .replace(/unit trust/g, '')
    .replace(/limited/g, '')
    .replace(/ltd/g, '')
    .replace(/pvt/g, '')
    .replace(/[^a-z0-9]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

export function findBestUtaslMatch(userFundName: string, list: UtaslFundPrice[] = fallbackUtaslFunds): UtaslFundPrice | null {
  if (!userFundName || userFundName.trim() === '' || list.length === 0) return null;

  const trimmed = userFundName.trim().toLowerCase();
  const normUser = normalize(userFundName);

  // 1. Exact match (case insensitive)
  const exact = list.find(it => it.fundName.toLowerCase() === trimmed);
  if (exact) return exact;

  // 2. Normalized exact match
  const normExact = list.find(it => normalize(it.fundName) === normUser);
  if (normExact) return normExact;

  // 3. Containment
  const containment = list.find(it => {
    const normCand = normalize(it.fundName);
    return normUser.includes(normCand) || normCand.includes(normUser);
  });
  if (containment) return containment;

  // 4. Token overlap matching
  const userTokens = new Set(normUser.split(' ').filter(t => t.length > 2));
  if (userTokens.size > 0) {
    let bestMatch: UtaslFundPrice | null = null;
    let maxOverlap = 0;
    for (const item of list) {
      const candidateTokens = new Set(normalize(item.fundName).split(' ').filter(t => t.length > 2));
      let intersectionCount = 0;
      for (const t of userTokens) {
        if (candidateTokens.has(t)) intersectionCount++;
      }
      if (intersectionCount > maxOverlap && intersectionCount >= 2) {
        maxOverlap = intersectionCount;
        bestMatch = item;
      }
    }
    if (bestMatch) return bestMatch;
  }

  return null;
}
